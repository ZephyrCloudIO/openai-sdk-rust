//! Grader namespace and shared grader model types.

use std::collections::HashMap;

use crate::Client;

/// Graders service root.
#[derive(Clone)]
pub struct GraderService {
    client: Client,
}

impl GraderService {
    pub(crate) fn new(client: Client) -> Self {
        Self { client }
    }

    /// Returns the grader model namespace service.
    #[must_use]
    pub fn grader_models(&self) -> GraderModelService {
        GraderModelService::new(self.client.clone())
    }
}

/// Grader model namespace.
#[derive(Clone)]
pub struct GraderModelService {
    client: Client,
}

impl GraderModelService {
    pub(crate) fn new(client: Client) -> Self {
        Self { client }
    }

    /// Returns an immutable reference to the parent client for future request APIs.
    #[must_use]
    pub fn client_ref(&self) -> &Client {
        &self.client
    }
}

