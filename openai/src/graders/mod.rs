/// Input content type used for grading.
#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum GraderInputType {
    /// Plain text input content.
    InputText,
    /// Text output generated by a model.
    OutputText,
    /// Image input content.
    InputImage,
    /// Audio input content.
    InputAudio,
}

/// Grader input payload.
#[derive(Debug, Clone, serde::Serialize, serde::Deserialize)]
pub struct GraderInput {
    /// Input variant type.
    #[serde(rename = "type")]
    pub input_type: GraderInputType,
    /// Text content when applicable.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub text: Option<String>,
    /// Image URL when `type` is `input_image`.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub image_url: Option<String>,
    /// Detail hint for image inputs (`low`/`high`/`auto`).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub detail: Option<String>,
}

/// One grader evaluation result.
#[derive(Debug, Clone, serde::Serialize, serde::Deserialize)]
pub struct GraderResult {
    /// Pass/fail outcome.
    pub pass: bool,
    /// Optional numeric score.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub score: Option<f32>,
    /// Optional explanatory rationale.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub rationale: Option<String>,
    /// Free-form provider metadata.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub metadata: Option<HashMap<String, serde_json::Value>>,
}

/// Grader response payload.
#[derive(Debug, Clone, serde::Serialize, serde::Deserialize)]
pub struct GraderResponse {
    /// Response ID.
    pub id: String,
    /// Object type.
    pub object: String,
    /// Evaluation results.
    pub results: Vec<GraderResult>,
}

